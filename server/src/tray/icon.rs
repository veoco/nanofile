//! Runtime tray icon, rasterized from `static/img/favicon.svg` at compile time
//! (see `build.rs`) — one raster per desktop theme, since the tile is near-black
//! on a light panel and near-white on a dark one. macOS gets the bare glyph,
//! because its menu bar inverts a template image itself.
//!
//! Windows keeps one raster per notification-area size: the shell asks for
//! `SM_CXSMICON` in device pixels, and a fixed 32px source is only exact at 200%
//! scaling.

use tray_icon::Icon;

#[cfg(not(target_os = "windows"))]
use super::icon_gen::TRAY_ICON_SIZE;
#[cfg(any(target_os = "windows", test))]
use super::icon_gen::TRAY_ICON_SIZES;

#[cfg(target_os = "windows")]
use windows_sys::Win32::UI::WindowsAndMessaging::{GetSystemMetrics, SM_CXSMICON};

#[cfg(target_os = "macos")]
pub(super) fn tray_icon() -> Icon {
    let rgba: &[u8] = TEMPLATE;
    Icon::from_rgba(rgba.to_vec(), TRAY_ICON_SIZE, TRAY_ICON_SIZE)
        .expect("tray icon raster does not match TRAY_ICON_SIZE — rebuild")
}

#[cfg(not(target_os = "macos"))]
pub(super) fn tray_icon() -> Icon {
    #[cfg(target_os = "windows")]
    let size = windows_icon_size();
    #[cfg(not(target_os = "windows"))]
    let size = TRAY_ICON_SIZE;

    icon_for_size(size, super::theme::is_dark())
}

/// The notification area's small-icon metric, in device pixels.
#[cfg(target_os = "windows")]
fn windows_icon_size() -> u32 {
    // A per-monitor-aware process gets the physical metric. 0 means there is no
    // usable desktop; the smallest raster is still better than a panic.
    let metric = unsafe { GetSystemMetrics(SM_CXSMICON) };
    nearest_icon_size(u32::try_from(metric).unwrap_or(0))
}

/// The generated edge length that covers `target` from above, so the shell never
/// has to upscale. Unknown sizes fall back to the largest raster.
#[cfg(any(target_os = "windows", test))]
fn nearest_icon_size(target: u32) -> u32 {
    let target = target.max(16);
    TRAY_ICON_SIZES
        .iter()
        .copied()
        .find(|&size| size >= target)
        .unwrap_or(*TRAY_ICON_SIZES.last().expect("tray sizes are not empty"))
}

/// Pick the light or dark raster for `size`; both files are generated by `build.rs`.
#[cfg(not(target_os = "macos"))]
macro_rules! theme_bytes {
    ($size:literal, $dark:expr) => {
        if $dark {
            include_bytes!(concat!(
                env!("OUT_DIR"),
                "/tray_icon_on_dark_",
                $size,
                ".rgba"
            ))
        } else {
            include_bytes!(concat!(
                env!("OUT_DIR"),
                "/tray_icon_on_light_",
                $size,
                ".rgba"
            ))
        }
    };
}

#[cfg(not(target_os = "macos"))]
fn icon_for_size(size: u32, dark: bool) -> Icon {
    let rgba: &[u8] = match size {
        16 => theme_bytes!(16, dark),
        20 => theme_bytes!(20, dark),
        24 => theme_bytes!(24, dark),
        28 => theme_bytes!(28, dark),
        32 => theme_bytes!(32, dark),
        36 => theme_bytes!(36, dark),
        40 => theme_bytes!(40, dark),
        48 => theme_bytes!(48, dark),
        56 => theme_bytes!(56, dark),
        64 => theme_bytes!(64, dark),
        _ => panic!("no tray icon raster for a {size}px icon"),
    };
    Icon::from_rgba(rgba.to_vec(), size, size)
        .unwrap_or_else(|e| panic!("tray icon raster for {size}px is invalid: {e:?}"))
}

#[cfg(target_os = "macos")]
const TEMPLATE: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/tray_icon_template.rgba"));

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_chosen_icon_never_needs_upscaling() {
        assert_eq!(nearest_icon_size(16), 16);
        assert_eq!(nearest_icon_size(20), 20);
        assert_eq!(nearest_icon_size(24), 24);
        assert_eq!(nearest_icon_size(28), 28);
        assert_eq!(nearest_icon_size(32), 32);
        assert_eq!(nearest_icon_size(36), 36);
        assert_eq!(nearest_icon_size(40), 40);
        assert_eq!(nearest_icon_size(48), 48);
        assert_eq!(nearest_icon_size(56), 56);
        assert_eq!(nearest_icon_size(64), 64);
        // Metrics below the smallest raster, or above the largest, clamp.
        assert_eq!(nearest_icon_size(0), 16);
        assert_eq!(nearest_icon_size(17), 20);
        assert_eq!(nearest_icon_size(70), 64);
    }
}
