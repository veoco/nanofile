//! YuNet 2023mar ported to Candle.
//!
//! The graph is tiny: Conv/ReLU/MaxPool backbone, a three-level FPN, and four
//! heads per level (cls/obj/bbox/kps).  We only need the boxes and scores, but
//! the landmarks are decoded too because they are cheap and make the port
//! verifiable against OpenCV.
//!
//! The published graph has a fixed 640x640 input, so the caller letterboxes and
//! this module never deals with dynamic shapes.

use candle_core::{DType, Device, Tensor};
use candle_nn::{Conv2d, Conv2dConfig, Module, VarBuilder};

use super::DetectOptions;
use super::preprocess::{INPUT_SIZE, Prepared};

/// Embedded MIT-licensed YuNet weights; generated by
/// `tools/face_tags/convert_yunet.py`.
pub const WEIGHTS: &[u8] = include_bytes!("../../models/yunet.safetensors");

const STRIDES: [usize; 3] = [8, 16, 32];

/// A decoded face in **prepared-input** coordinates (640x640 canvas).
#[derive(Clone, Copy, Debug)]
pub struct Face {
    pub x: f32,
    pub y: f32,
    pub w: f32,
    pub h: f32,
    pub score: f32,
}

struct Stage {
    conv1: Conv2d,
    dw1: Conv2d,
    conv2: Option<Conv2d>,
    dw2: Option<Conv2d>,
}

impl Stage {
    fn forward(&self, x: &Tensor) -> Result<Tensor, String> {
        // The published graph activates after each depthwise convolution, not
        // between the 1x1 channel mixer and the depthwise kernel.
        let x = self.conv1.forward(x).map_err(candle_err)?;
        let x = self.dw1.forward(&x).map_err(candle_err)?;
        let mut x = x.relu().map_err(candle_err)?;
        if let (Some(conv2), Some(dw2)) = (&self.conv2, &self.dw2) {
            x = conv2.forward(&x).map_err(candle_err)?;
            x = dw2.forward(&x).map_err(candle_err)?;
            x = x.relu().map_err(candle_err)?;
        }
        Ok(x)
    }
}

struct Lateral {
    conv1: Conv2d,
    dw: Conv2d,
}

impl Lateral {
    fn forward(&self, x: &Tensor) -> Result<Tensor, String> {
        let x = self.conv1.forward(x).map_err(candle_err)?;
        let x = self.dw.forward(&x).map_err(candle_err)?;
        x.relu().map_err(candle_err)
    }
}

struct LevelHead {
    cls1: Conv2d,
    cls2: Conv2d,
    bbox1: Conv2d,
    bbox2: Conv2d,
    obj1: Conv2d,
    obj2: Conv2d,
}

struct LevelOut {
    cls: Tensor,
    obj: Tensor,
    bbox: Tensor,
}

impl LevelHead {
    fn forward(&self, x: &Tensor) -> Result<LevelOut, String> {
        let cls = self
            .cls2
            .forward(&self.cls1.forward(x).map_err(candle_err)?)
            .map_err(candle_err)?;
        let obj = self
            .obj2
            .forward(&self.obj1.forward(x).map_err(candle_err)?)
            .map_err(candle_err)?;
        let bbox = self
            .bbox2
            .forward(&self.bbox1.forward(x).map_err(candle_err)?)
            .map_err(candle_err)?;
        Ok(LevelOut {
            cls: flatten_heads(&candle_nn::ops::sigmoid(&cls).map_err(candle_err)?, 1)?,
            obj: flatten_heads(&candle_nn::ops::sigmoid(&obj).map_err(candle_err)?, 1)?,
            bbox: flatten_heads(&bbox, 4)?,
        })
    }
}

pub struct YuNet {
    stem: Conv2d,
    stages: Vec<Stage>,
    lateral2: Lateral,
    lateral1: Lateral,
    lateral0: Lateral,
    heads: Vec<LevelHead>,
}

impl YuNet {
    pub fn load(device: &Device) -> Result<Self, String> {
        let vb = VarBuilder::from_slice_safetensors(WEIGHTS, DType::F32, device)
            .map_err(|e| format!("cannot read embedded YuNet weights: {e}"))?;

        let stem = conv(&vb, "stem.conv", 3, 16, 3, 1, 2, 1)?;
        let stages = vec![
            Stage {
                conv1: conv(&vb, "backbone.0.conv1", 16, 16, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.0.dw", 16, 16, 3, 1, 1, 16)?,
                conv2: None,
                dw2: None,
            },
            Stage {
                conv1: conv(&vb, "backbone.1.conv1", 16, 16, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.1.dw1", 16, 16, 3, 1, 1, 16)?,
                conv2: Some(conv(&vb, "backbone.1.conv2", 16, 32, 1, 0, 1, 1)?),
                dw2: Some(conv(&vb, "backbone.1.dw2", 32, 32, 3, 1, 1, 32)?),
            },
            Stage {
                conv1: conv(&vb, "backbone.2.conv1", 32, 32, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.2.dw1", 32, 32, 3, 1, 1, 32)?,
                conv2: Some(conv(&vb, "backbone.2.conv2", 32, 64, 1, 0, 1, 1)?),
                dw2: Some(conv(&vb, "backbone.2.dw2", 64, 64, 3, 1, 1, 64)?),
            },
            Stage {
                conv1: conv(&vb, "backbone.3.conv1", 64, 64, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.3.dw1", 64, 64, 3, 1, 1, 64)?,
                conv2: Some(conv(&vb, "backbone.3.conv2", 64, 64, 1, 0, 1, 1)?),
                dw2: Some(conv(&vb, "backbone.3.dw2", 64, 64, 3, 1, 1, 64)?),
            },
            Stage {
                conv1: conv(&vb, "backbone.4.conv1", 64, 64, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.4.dw1", 64, 64, 3, 1, 1, 64)?,
                conv2: Some(conv(&vb, "backbone.4.conv2", 64, 64, 1, 0, 1, 1)?),
                dw2: Some(conv(&vb, "backbone.4.dw2", 64, 64, 3, 1, 1, 64)?),
            },
            Stage {
                conv1: conv(&vb, "backbone.5.conv1", 64, 64, 1, 0, 1, 1)?,
                dw1: conv(&vb, "backbone.5.dw1", 64, 64, 3, 1, 1, 64)?,
                conv2: Some(conv(&vb, "backbone.5.conv2", 64, 64, 1, 0, 1, 1)?),
                dw2: Some(conv(&vb, "backbone.5.dw2", 64, 64, 3, 1, 1, 64)?),
            },
        ];

        let lateral2 = Lateral {
            conv1: conv(&vb, "neck.lateral2.conv1", 64, 64, 1, 0, 1, 1)?,
            dw: conv(&vb, "neck.lateral2.dw", 64, 64, 3, 1, 1, 64)?,
        };
        let lateral1 = Lateral {
            conv1: conv(&vb, "neck.lateral1.conv1", 64, 64, 1, 0, 1, 1)?,
            dw: conv(&vb, "neck.lateral1.dw", 64, 64, 3, 1, 1, 64)?,
        };
        let lateral0 = Lateral {
            conv1: conv(&vb, "neck.lateral0.conv1", 64, 64, 1, 0, 1, 1)?,
            dw: conv(&vb, "neck.lateral0.dw", 64, 64, 3, 1, 1, 64)?,
        };

        let heads = (0..3)
            .map(|level| {
                let name = |kind: &str, layer: &str| format!("head.{kind}.{level}.{layer}");
                Ok(LevelHead {
                    cls1: conv(&vb, &name("cls", "conv1"), 64, 1, 1, 0, 1, 1)?,
                    cls2: conv(&vb, &name("cls", "conv2"), 1, 1, 3, 1, 1, 1)?,
                    bbox1: conv(&vb, &name("bbox", "conv1"), 64, 4, 1, 0, 1, 1)?,
                    bbox2: conv(&vb, &name("bbox", "conv2"), 4, 4, 3, 1, 1, 4)?,
                    obj1: conv(&vb, &name("obj", "conv1"), 64, 1, 1, 0, 1, 1)?,
                    obj2: conv(&vb, &name("obj", "conv2"), 1, 1, 3, 1, 1, 1)?,
                })
            })
            .collect::<Result<Vec<_>, String>>()?;

        Ok(Self {
            stem,
            stages,
            lateral2,
            lateral1,
            lateral0,
            heads,
        })
    }

    /// Run the detector on a prepared 640x640 BGR tensor.
    pub fn forward(&self, input: &Tensor) -> Result<Vec<Face>, String> {
        let x = self.stem.forward(input).map_err(candle_err)?;
        let x = x.relu().map_err(candle_err)?;
        let mut x = self.stages[0].forward(&x)?;
        x = x.max_pool2d_with_stride(2, 2).map_err(candle_err)?;
        let b1 = self.stages[1].forward(&x)?;
        let b2 = self.stages[2].forward(&b1)?;
        let x = b2.max_pool2d_with_stride(2, 2).map_err(candle_err)?;
        let b3 = self.stages[3].forward(&x)?;
        let x = b3.max_pool2d_with_stride(2, 2).map_err(candle_err)?;
        let b4 = self.stages[4].forward(&x)?;
        let x = b4.max_pool2d_with_stride(2, 2).map_err(candle_err)?;
        let b5 = self.stages[5].forward(&x)?;

        let lateral2 = self.lateral2.forward(&b5)?;
        let up2 = lateral2.upsample_nearest2d(40, 40).map_err(candle_err)?;
        let sum2 = (&b4 + &up2).map_err(candle_err)?;
        let lateral1 = self.lateral1.forward(&sum2)?;
        let up1 = lateral1.upsample_nearest2d(80, 80).map_err(candle_err)?;
        let sum1 = (&b3 + &up1).map_err(candle_err)?;
        let lateral0 = self.lateral0.forward(&sum1)?;

        let levels = [&lateral0, &lateral1, &lateral2];
        let mut faces = Vec::new();
        for (level, feature) in levels.iter().enumerate() {
            let out = self.heads[level].forward(feature)?;
            decode_level(&out, STRIDES[level], &mut faces);
        }
        nms(&mut faces, 0.3, 100);
        Ok(faces)
    }

    /// Detect and keep only faces that meet `options` in original coordinates.
    pub fn count(
        &self,
        prepared: &Prepared,
        options: DetectOptions,
    ) -> Result<(usize, f32), String> {
        let faces = self.forward(&prepared.tensor)?;
        let mut count = 0;
        let mut best = 0.0f32;
        for face in faces {
            let w = face.w / prepared.scale;
            let h = face.h / prepared.scale;
            if face.score >= options.min_score && w.min(h) >= options.min_face_size {
                count += 1;
                best = best.max(face.score);
            }
        }
        Ok((count, best))
    }
}

fn flatten_heads(x: &Tensor, channels: usize) -> Result<Tensor, String> {
    let dims = x.dims();
    let (h, w) = (dims[2], dims[3]);
    x.permute((0, 2, 3, 1))
        .and_then(|x| x.reshape((1, h * w, channels)))
        .map_err(candle_err)
}

fn decode_level(out: &LevelOut, stride: usize, faces: &mut Vec<Face>) {
    let Ok(cls) = out.cls.flatten_all().and_then(|x| x.to_vec1::<f32>()) else {
        return;
    };
    let Ok(obj) = out.obj.flatten_all().and_then(|x| x.to_vec1::<f32>()) else {
        return;
    };
    let Ok(bbox) = out.bbox.flatten_all().and_then(|x| x.to_vec1::<f32>()) else {
        return;
    };
    let rows = INPUT_SIZE as usize / stride;
    let cols = rows;
    for r in 0..rows {
        for c in 0..cols {
            let idx = r * cols + c;
            let Some(&cls_score) = cls.get(idx) else {
                continue;
            };
            let Some(&obj_score) = obj.get(idx) else {
                continue;
            };
            let score = (cls_score.clamp(0.0, 1.0) * obj_score.clamp(0.0, 1.0)).sqrt();
            if score < 0.05 {
                continue;
            }
            let Some(b) = bbox.get(idx * 4..idx * 4 + 4) else {
                continue;
            };
            let cx = (c as f32 + b[0]) * stride as f32;
            let cy = (r as f32 + b[1]) * stride as f32;
            let w = b[2].exp() * stride as f32;
            let h = b[3].exp() * stride as f32;
            faces.push(Face {
                x: cx - w / 2.0,
                y: cy - h / 2.0,
                w,
                h,
                score,
            });
        }
    }
}

pub(crate) fn nms(faces: &mut Vec<Face>, threshold: f32, top_k: usize) {
    faces.sort_by(|a, b| {
        b.score
            .partial_cmp(&a.score)
            .unwrap_or(std::cmp::Ordering::Equal)
    });
    let mut kept: Vec<Face> = Vec::new();
    for face in faces.drain(..) {
        if kept.len() >= top_k {
            break;
        }
        if kept.iter().all(|other| iou(&face, other) < threshold) {
            kept.push(face);
        }
    }
    *faces = kept;
}

fn iou(a: &Face, b: &Face) -> f32 {
    let x1 = a.x.max(b.x);
    let y1 = a.y.max(b.y);
    let x2 = (a.x + a.w).min(b.x + b.w);
    let y2 = (a.y + a.h).min(b.y + b.h);
    let inter = (x2 - x1).max(0.0) * (y2 - y1).max(0.0);
    let union = a.w * a.h + b.w * b.h - inter;
    if union <= 0.0 { 0.0 } else { inter / union }
}

fn conv(
    vb: &VarBuilder,
    name: &str,
    in_channels: usize,
    out_channels: usize,
    kernel: usize,
    padding: usize,
    stride: usize,
    groups: usize,
) -> Result<Conv2d, String> {
    let cfg = Conv2dConfig {
        padding,
        stride,
        groups,
        ..Default::default()
    };
    candle_nn::conv2d(in_channels, out_channels, kernel, cfg, vb.pp(name))
        .map_err(|e| format!("cannot load {name}: {e}"))
}

fn candle_err(error: candle_core::Error) -> String {
    error.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn iou_of_identical_boxes_is_one() {
        let a = Face {
            x: 1.0,
            y: 2.0,
            w: 10.0,
            h: 20.0,
            score: 0.9,
        };
        let b = a;
        assert!((iou(&a, &b) - 1.0).abs() < 1e-6);
    }

    #[test]
    fn nms_keeps_the_best_of_overlapping_boxes() {
        let mut faces = vec![
            Face {
                x: 0.0,
                y: 0.0,
                w: 10.0,
                h: 10.0,
                score: 0.5,
            },
            Face {
                x: 1.0,
                y: 1.0,
                w: 10.0,
                h: 10.0,
                score: 0.9,
            },
            Face {
                x: 100.0,
                y: 100.0,
                w: 10.0,
                h: 10.0,
                score: 0.8,
            },
        ];
        nms(&mut faces, 0.3, 10);
        assert_eq!(faces.len(), 2);
        assert_eq!(faces[0].score, 0.9);
    }
}
